func applyExplicitLogTextFilter(tx *gorm.DB, column string, value string) (*gorm.DB, error) {
	if value == "" {
		return tx, nil
	}
	if strings.Contains(value, "%") {
		condition, pattern, err := buildLogLikeCondition(column, value)
		if err != nil {
			return nil, err
		}
		return tx.Where(condition, pattern), nil
	}
	return tx.Where(column+" = ?", value), nil
}

// applyLogModelFilter 支持多模型精确过滤（modelNames）与单模型模糊过滤（modelName）。
func applyLogModelFilter(tx *gorm.DB, column string, modelName string, modelNames []string) (*gorm.DB, error) {
	if len(modelNames) > 0 {
		return tx.Where(column+" IN ?", modelNames), nil
	}
	if modelName != "" {
		modelNamePattern, err := sanitizeLikePattern(modelName)
		if err != nil {
			return nil, err
		}
		return tx.Where(column+" LIKE ? ESCAPE '!'", modelNamePattern), nil
	}
	return tx, nil
}

// applyLogModelExcludeFilter 排除指定模型，用于把生图等专用模型的日志从通用日志中分离出去。
func applyLogModelExcludeFilter(tx *gorm.DB, column string, excludeModelNames []string) *gorm.DB {
	if len(excludeModelNames) == 0 {
		return tx
	}
	return tx.Where(column+" NOT IN ?", excludeModelNames)
}

func buildLogLikeCondition(column string, value string) (string, string, error) {
	if common.UsingLogDatabase(common.DatabaseTypeClickHouse) {
		pattern, err := sanitizeClickHouseLikePattern(value)
		if err != nil {
			return "", "", err
		}
		return column + " LIKE ?", pattern, nil
	}

	pattern, err := sanitizeLikePattern(value)
	if err != nil {
		return "", "", err
	}
	return column + " LIKE ? ESCAPE '!'", pattern, nil
}

func sanitizeClickHouseLikePattern(input string) (string, error) {
	input = strings.ReplaceAll(input, `\`, `\\`)
	input = strings.ReplaceAll(input, `_`, `\_`)

	if err := validateLikePattern(input); err != nil {
		return "", err
	}
	return input, nil
}

